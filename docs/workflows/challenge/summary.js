// Nightly report to the founder: what happened today, and anything that needs a decision.
const ctl = Object.fromEntries($('Read Control').all().map(i => [i.json.key, i.json.value]));
const now = Date.now();
const dz = t => new Date(new Date(t).getTime() + 3600e3).toISOString().slice(0, 10);
const today = dz(now);
const week = ctl.active_week;
const plan = $('Read Plan').all().map(i => i.json).filter(r => r.row_key);
const mine = plan.filter(r => r.week === week);
const chk = $('Read Checkins').all().map(i => i.json).filter(c => c.week === week);
const acts = $('Read Actions').all().map(i => i.json).filter(a => a.at && dz(a.at) === today);
const inbox = $('Read Inbox').all().map(i => i.json).filter(m => m.at && now - new Date(m.at).getTime() < 24 * 3600e3);
const start = Date.parse((ctl.challenge_start || '2099-01-01') + 'T00:00:00Z');
const night = Math.round((Date.parse(today + 'T00:00:00Z') - start) / 864e5) + 1;
const per = {}; for (const c of chk) per[c.night] = (per[c.night] || 0) + 1;
const people = {}; for (const c of chk) people[c.participant] = (people[c.participant] || 0) + 1;
const onTrack = Object.values(people).filter(n => n >= Math.max(1, night - 1)).length;
const sentToday = mine.filter(r => r.sent_at && dz(r.sent_at) === today && r.status === 'sent').length;
const failed = mine.filter(r => r.status === 'failed' || r.status === 'missed');
const tomorrow = dz(now + 864e5);
const tmr = plan.filter(r => r.post_at && dz(r.post_at) === tomorrow);
const notApproved = tmr.filter(r => r.status === 'draft');
const n = k => acts.filter(a => a.kind === k).length;
const lines = [`🌙 <b>تقرير اليوم ${today}</b>`];
if (night >= 1 && night <= 8) lines.push(`الليلة ${Math.min(night, 7)} · ✅ الليلة: ${per[night] || 0} · أمهات ماشيات في التحدّي: ${onTrack}`);
lines.push(`منشورات اليوم: ${sentToday} · ردود نور: ${n('reply')} · تحويل للخاص: ${n('dm')} · تنبيهات: ${n('alert')}`);
lines.push(`رسائل المجموعة آخر 24 ساعة: ${inbox.length}`);
if (failed.length) lines.push(`⚠️ لم يُنشر: ${failed.map(r => r.row_key).join('، ')}`);
if (notApproved.length) lines.push(`⏳ منشورات الغد غير موافق عليها (${notApproved.length}): لن تُنشر. صفحة المراجعة: https://adam-voices-n8n.hawiyat.cloud/webhook/adam-review?t=${ctl.review_token}`);
if (night >= 1 && night <= 7 && inbox.length === 0) lines.push('⚠️ لم تصل أي رسالة من المجموعة منذ 24 ساعة. قد يكون اشتراك وابيتو متوقفاً.');
if (String(ctl.paused) === 'true') lines.push('⏸ النظام كله موقوف الآن (paused).');
if (String(ctl.brain_on) !== 'true') lines.push('💤 ردود نور في المجموعة متوقفة (brain_on).');
const future = plan.filter(r => r.post_at && new Date(r.post_at).getTime() > now && r.status !== 'skipped');
if (future.length === 0) lines.push('📭 لا يوجد أي منشور قادم. جهّز تحدّي الأسبوع القادم.');
return [{ json: { op: 'telegram', text: lines.join('\n').slice(0, 3900) } }];
