const SYSTEM_TEMPLATE = $getWorkflowStaticData('global').sysTemplate || '';
if (!SYSTEM_TEMPLATE) return [];

const PRICING = [
  '- «من الصرخة إلى الحضن»: 9$ دفعة واحدة، https://hodn.adamvoices.site (للأم التي تصرخ ثم تندم)',
  '- «وراء كلّ لا حكاية»: 12$ دفعة واحدة، https://inad.adamvoices.site (لطفل 2–7 عنيد)',
  '- «بطاقات مشاعر آدم»: 7$ دفعة واحدة، https://adamvoices.site/cards (لطفل 3–8 لا يعبّر، نوبات، ضرب)',
  '- برنامج «21 يوماً لبيت أهدأ»: ليس للبيع الآن، قائمة انتظار فقط https://adamvoices.site/21 (الصباح، النوم، الشاشة). لا تذكري له سعراً ولا موعداً.',
  '- الدفع بالبطاقة أو Apple Pay من صفحة المنتج، ويصل فوراً. السعر بعملة بلدها يظهر في الصفحة.',
  '- الجزائر: «من الصرخة إلى الحضن» بـ 1,900 دج. التحويل عبر CCP باسم لغويل عبد المعز، الرقم 00799999002824585207، ثم ترسل صورة الوصل هنا ويصلها الدفتر خلال دقائق. أو الدفع الفوري بالذهبية / CIB من صفحة الدفتر (قسم الجزائر). هذه طريقة مؤكّدة: أعطيها مباشرة، بلا «سأتحقق».',
  '- لا تذكري أسعاراً غير هذه. إن سألت عن طريقة دفع محلية لبلد آخر، أو عن منتج آخر بالدينار، قولي: «سيرسل لكِ الفريق طريقة الدفع هنا بعد قليل» واجعلي escalate = true. لا تقولي «سأتحقق» دون escalate.'
].join('\n');

return $input.all().map(it => {
  const d = it.json;
  const hist = d.history || [];
  const toText = c => Array.isArray(c) ? c.map(p => p.type === 'text' ? p.text : '').join(' ') : String(c ?? '');
  const userTexts = hist.filter(m => m.role === 'user').map(m => toText(m.content)).join(' ');
  const botTexts = hist.filter(m => m.role === 'assistant').map(m => toText(m.content)).join(' ');
  
  // تحليل سياق المحادثة السابق بدقة
  const hasSpecificAdvice = /جرّبي|تمرين|خيارين|أنفاس|الغليان|الخطوة|الطلب القريب|دقيقة تهدئة/.test(botTexts);
  const onlyAskedLinkOrPrice = /دفتر|رابط|سعر|بكم|شحال|ثمن/.test(userTexts) && !/عصبي|صراخ|عناد|نوم|دراسة|مراجعة|يضرب|يبكي|مهبلني/.test(userTexts);

  const PRODUCT_NAMES = { hodn: '«من الصرخة إلى الحضن»', inad: '«وراء كلّ لا حكاية»', cards: '«بطاقات مشاعر آدم»' };
  const algeria = /الجزائر|algeria|dz/i.test(String(d.country || ''));
  let scenarioGuide = '';
  if (d.offered && PRODUCT_NAMES[d.offered]) {
    scenarioGuide = '- سياق المحادثة: عرضتِ عليها ' + PRODUCT_NAMES[d.offered] + ' ولم تشترِ بعد.\n' +
      '- المطلوب: رسالة متابعة مهنية هادئة، كأخت تطمئن، لا كبائعة. ابدئي بها هي أو بطفلها وبالموقف الذي حكت عنه (سؤال واحد محدد عن حالها اليوم).\n' +
      '- ثم سطر واحد فقط يفتح الباب: أنكِ هنا إن كان عندها سؤال عن ' + PRODUCT_NAMES[d.offered] + ' أو عن طريقة الدفع.' + (algeria && d.offered === 'hodn' ? ' هي من الجزائر: اذكري بلطف أن الدفع ممكن عبر CCP بـ 1,900 دج إن كان هذا ما أوقفها، دون كتابة رقم الحساب إلا إن سألت.' : '') + '\n' +
      '- ممنوع: إعادة السعر بالدولار، الإلحاح، «العرض ينتهي»، «آخر فرصة»، «هل اشتريتِ؟»، أو إعادة إرسال الرابط. إن احتاجت الرابط ستطلبه.\n' +
      '- إن ظهر في السجل أنها قالت إنها لا تستطيع الآن أو اعتذرت، فلا تذكري المنتج إطلاقاً: اطمئني عليها فقط.';
  } else if (onlyAskedLinkOrPrice || !hasSpecificAdvice) {
    scenarioGuide = '- سياق المحادثة: المتابع سأل فقط عن الدفتر أو الرابط أو لم يتم إعطاؤه فكرة تربوية سابقة.\n- المطلوب في رسالة المتابعة: اطمئني عليه بلطف بخصوص الرابط فقط، مثل: «أهلاً أختي 🤍 حبيت أطمئن فقط إن كان رابط الدفتر فتح معكِ تماماً، وإذا عندك أي استفسار أنا معكِ بأي وقت». إياكِ إطلاقاً أن تسألي: (هل جربتِ الفكرة التي حكينا عنها؟) لأنه لا توجد فكرة سابقة!';
  } else {
    scenarioGuide = '- سياق المحادثة: تمت مناقشة سلوك أو موقف تربوي سابقاً.\n- المطلوب في رسالة المتابعة: اسأليها بلطف شديد ومحدد عن ذلك الموقف بعينه (مثلاً: إن كان عن العناد أو وقت المذاكرة أو الهدوء)، دون استخدام عبارة عامة وغامضة، وبدون أي ضغط بيعي.';
  }

  const system = SYSTEM_TEMPLATE.replace('{{PRICING}}', PRICING) +
    '\n\n# مهمة خاصة: رسالة متابعة واحدة (Follow-up)\nالمتابعة سكتت منذ قرابة يوم. اكتبي رسالة متابعة واحدة قصيرة جداً (سطرين) بلا أي ضغط بيعي وبلا إلحاح. هذه آخر رسالة منك إن لم ترد.\n' +
    scenarioGuide +
    '\n\n# قواعد النداء في المتابعة:\n- نادي بالاسم البشري الواضح فقط إن كان مفهوماً وصريحاً (الأول أو الأخير). إن كان الاسم إنجليزياً أو مبهماً أو كنية، نادي بـ «أختي» (لا تقولي عزيزتي لتجنب سوء الظن، وممنوع نهائياً تركيب \"يا أم [اسم الحساب]\")!' +
    '\n- تاريخ اليوم: ' + new Date().toISOString().slice(0, 10) +
    '\n- الاسم المسجل: ' + (d.name || 'غير معروف') +
    '\n- آخر مرحلة: ' + d.stage;

  return { json: { ...d, payload: {
    model: 'openai/gpt-5',
    messages: [{ role: 'system', content: system }, ...hist, { role: 'user', content: '[لا رسالة جديدة: اقرئي سجل المحادثة جيداً واكتبي رسالة المتابعة الذكية المتوافقة مع السياق الآن]' }],
    reasoning: { effort: 'low' },
    response_format: { type: 'json_object' }
  }}};
});
