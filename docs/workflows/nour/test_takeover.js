const fs=require('fs');const code=fs.readFileSync(__dirname+'/Takeover-Human-Active.js','utf8');
const run=(msgs,prof)=>new Function('$input','$',code)({first:()=>({json:prof||{}})},n=>({first:()=>({json:n==='Takeover: Recent Messages'?(msgs===null?{error:'x'}:{messages:msgs}):{conversationId:'c',jobId:'j'}})}))[0].json;
const now=Date.now(), ago=m=>new Date(now-m*60000).toISOString();
let f=0;const ok=(n,c,i)=>{console.log((c?'PASS ':'FAIL ')+n+(c?'':' -> '+i));if(!c)f++;};
let r=run([{direction:'incoming',message:'وكيفاش نخلص؟',createdAt:ago(0)},{direction:'outgoing',sentVia:null,message:'هذا هو ccp',createdAt:ago(10)},{direction:'outgoing',sentVia:'api',message:'مرحبا',createdAt:ago(20)}]);
ok('human reply 10 min ago pauses Nour',r.humanActive===true,JSON.stringify(r));
ok('history labels founder line',r.platformHistory.includes('الفريق (إنسان): هذا هو ccp')&&r.platformHistory.includes('نور: مرحبا'),r.platformHistory);
ok('current incoming batch excluded',!r.platformHistory.includes('وكيفاش نخلص'),r.platformHistory);
r=run([{direction:'incoming',message:'سلام',createdAt:ago(0)},{direction:'outgoing',sentVia:null,message:'قديم',createdAt:ago(45)}]);
ok('human reply 45 min ago does not pause',r.humanActive===false,'');
r=run([{direction:'outgoing',sentVia:'api',message:'nour',createdAt:ago(2)}]);
ok('Nour own reply does not pause',r.humanActive===false,'');
r=run(null);
ok('Zernio failure -> no pause, empty history',r.humanActive===false&&r.platformHistory===''&&r.zernioOk===false,JSON.stringify(r));
r=run([],{ok:true,profile:{country:'الجزائر'}});
ok('profile passed through',r.profile&&r.profile.country==='الجزائر',JSON.stringify(r.profile));
r=run([],{error:'timeout'});
ok('profile fetch failure -> null profile',r.profile===null,'');
console.log(f?f+' FAILED':'ALL PASSED');process.exit(f?1:0);
